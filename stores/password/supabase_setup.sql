-- إنشاء الطلب وحفظ تفاصيل المنتجات يتمان في معاملة واحدة مع اعتماد الأسعار من قاعدة البيانات.
create or replace function public.create_store_order(
  p_customer_name text,
  p_customer_phone text,
  p_payment_method text,
  p_delivery_method text,
  p_delivery_address text,
  p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_order_id uuid;
  v_subtotal numeric(10,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول أولاً'; end if;
  if length(trim(coalesce(p_customer_name,''))) < 5 then raise exception 'اكتب الاسم الثلاثي'; end if;
  if length(trim(coalesce(p_customer_phone,''))) < 7 then raise exception 'اكتب رقم هاتف صحيح'; end if;
  if p_payment_method not in ('cash_on_delivery','instapay','vodafone_cash','orange_cash','etisalat_cash','we_pay','other_wallet') then raise exception 'وسيلة الدفع غير صحيحة'; end if;
  if p_delivery_method not in ('pickup','home_delivery') then raise exception 'طريقة الاستلام غير صحيحة'; end if;
  if p_delivery_method='home_delivery' and length(trim(coalesce(p_delivery_address,''))) < 8 then raise exception 'اكتب عنوان التوصيل بالتفصيل'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then raise exception 'السلة فارغة'; end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := greatest(1, least(99, (v_item->>'quantity')::integer));
    select * into v_product from public.products where id=(v_item->>'product_id')::bigint and available=true;
    if not found then raise exception 'أحد المنتجات لم يعد متاحاً'; end if;
    v_subtotal := v_subtotal + (v_product.price * v_qty);
  end loop;

  insert into public.store_orders(user_id,customer_name,customer_phone,payment_method,delivery_method,delivery_address,subtotal,total,status)
  values(auth.uid(),trim(p_customer_name),trim(p_customer_phone),p_payment_method,p_delivery_method,nullif(trim(p_delivery_address),''),v_subtotal,null,'new')
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_qty := greatest(1, least(99, (v_item->>'quantity')::integer));
    select * into v_product from public.products where id=(v_item->>'product_id')::bigint and available=true;
    insert into public.store_order_items(order_id,product_id,product_name,unit_price,quantity,line_total)
    values(v_order_id,v_product.id,v_product.name,v_product.price,v_qty,v_product.price*v_qty);
  end loop;
  return v_order_id;
end;
$$;
revoke all on function public.create_store_order(text,text,text,text,text,jsonb) from public;
grant execute on function public.create_store_order(text,text,text,text,text,jsonb) to authenticated;

create or replace function public.set_store_order_receipt(p_order_id uuid,p_receipt_path text)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null then raise exception 'يجب تسجيل الدخول'; end if;
  if p_receipt_path not like auth.uid()::text || '/' || p_order_id::text || '/%' then raise exception 'مسار الإيصال غير صحيح'; end if;
  update public.store_orders set receipt_path=p_receipt_path,updated_at=now()
  where id=p_order_id and user_id=auth.uid() and payment_method <> 'cash_on_delivery';
  if not found then raise exception 'الطلب غير موجود أو لا يقبل إيصالاً'; end if;
end;
$$;
revoke all on function public.set_store_order_receipt(uuid,text) from public;
grant execute on function public.set_store_order_receipt(uuid,text) to authenticated;

