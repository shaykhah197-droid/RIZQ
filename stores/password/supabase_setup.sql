create table if not exists public.store_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  customer_name text not null,
  customer_phone text not null,
  payment_method text not null check (payment_method in ('cash_on_delivery','instapay','vodafone_cash','orange_cash','etisalat_cash','we_pay','other_wallet')),
  delivery_method text not null check (delivery_method in ('pickup','home_delivery')),
  delivery_address text,
  delivery_fee numeric(10,2),
  subtotal numeric(10,2) not null default 0,
  total numeric(10,2),
  status text not null default 'new' check (status in ('new','reviewing','awaiting_payment','confirmed','preparing','out_for_delivery','completed','cancelled')),
  receipt_path text,
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint home_delivery_requires_address check (delivery_method <> 'home_delivery' or nullif(trim(delivery_address),'') is not null)
);

create table if not exists public.store_order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.store_orders(id) on delete cascade,
  product_id bigint,
  product_name text not null,
  unit_price numeric(10,2) not null,
  quantity integer not null check (quantity between 1 and 99),
  line_total numeric(10,2) not null
);

create table if not exists public.store_payment_methods (
  id bigint generated by default as identity primary key,
  method_code text not null unique check (method_code in ('instapay','vodafone_cash','orange_cash','etisalat_cash','we_pay','other_wallet')),
  display_name text not null,
  account_name text,
  account_number text,
  instructions text,
  enabled boolean not null default false,
  updated_at timestamptz not null default now()
);

